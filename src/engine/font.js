// Draws every glyph into one strip texture, then registers it as bitmap font 'px'.
SA.buildFont = function (scene) {
  const chars = SA.FONT_CHARS, cw = 6, ch = 8;
  const tex = scene.textures.createCanvas('pxfont', cw * chars.length, ch);
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  for (let i = 0; i < chars.length; i++) {
    const rows = SA.FONT_GLYPHS[chars[i]];
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        if (rows[y] & (0x10 >> x)) ctx.fillRect(i * cw + x, y, 1, 1);
      }
    }
  }
  tex.refresh();
  const data = Phaser.GameObjects.RetroFont.Parse(scene, {
    image: 'pxfont', width: cw, height: ch, chars, charsPerRow: chars.length,
    offset: { x: 0, y: 0 }, spacing: { x: 0, y: 0 }, lineSpacing: 2,
  });
  scene.cache.bitmapFont.add('px', data);
};

// Text helper. Lowercase is shown as uppercase; unknown characters become spaces.
SA.clean = (s) => String(s).toUpperCase().split('').map((c) => (c === '\n' || SA.FONT_GLYPHS[c] ? c : ' ')).join('');
SA.text = function (scene, x, y, str, color = SA.C.white, scale = 1) {
  const t = scene.add.bitmapText(x, y, 'px', SA.clean(str)).setTint(color).setScale(scale);
  return t;
};
// Centered text with an optional 1px drop shadow for readability.
SA.ctext = function (scene, x, y, str, color = SA.C.white, scale = 1, shadow = true) {
  let sh = null;
  if (shadow) sh = SA.text(scene, x + scale, y + scale, str, SA.C.ink, scale).setOrigin(0.5, 0);
  const t = SA.text(scene, x, y, str, color, scale).setOrigin(0.5, 0);
  t.shadow = sh;
  t.setAll = (s) => { t.setText(SA.clean(s)); if (sh) sh.setText(SA.clean(s)); };
  return t;
};
